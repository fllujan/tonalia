// Generate src/lib/rpc.types.ts from engine/tonalia_engine/rpc_schema.py.
// Usage: node scripts/gen-types.mjs [--check]
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const engineDir = resolve(here, "../../engine");
const outFile = resolve(here, "../src/lib/rpc.types.ts");
const ROOT = "RpcSchemaRoot";

const raw = execFileSync("uv", ["run", "--quiet", "python", "-m", "tonalia_engine.schema_export"], {
  cwd: engineDir,
  encoding: "utf8",
  shell: process.platform === "win32",
});
const contract = JSON.parse(raw);

// Pydantic titles every property, which would emit one alias type per field
// (e.g. `type Pong = boolean`). Keep titles only at the model level.
function stripPropertyTitles(node, isModel = true) {
  if (Array.isArray(node)) return node.forEach((n) => stripPropertyTitles(n, false));
  if (!node || typeof node !== "object") return;
  if (!isModel) delete node.title;
  for (const [key, value] of Object.entries(node)) {
    if (key === "$defs") Object.values(value).forEach((d) => stripPropertyTitles(d, true));
    else if (key !== "title") stripPropertyTitles(value, false);
  }
}
stripPropertyTitles({ $defs: contract.$defs });

let body = await compile(
  { title: ROOT, type: "object", additionalProperties: false, $defs: contract.$defs },
  ROOT,
  { bannerComment: "", unreachableDefinitions: true, additionalProperties: false },
);
// Drop the synthetic root interface; keep only the model interfaces.
body = body
  .replace(new RegExp(`export interface ${ROOT} \\{\\}\\n*`), "")
  .replace(/\/\*\*\n \* This interface was referenced by[^/]*\*\/\n/g, "")
  .trim();

const methods = Object.entries(contract.methods)
  .map(([name, m]) => `  "${name}": { params: ${m.params ?? "null"}; result: ${m.result} };`)
  .join("\n");
const notifications = Object.entries(contract.notifications)
  .map(([name, model]) => `  ${name}: ${model};`)
  .join("\n");
const events = Object.entries(contract.events)
  .map(([name, model]) => `  "${name}": ${model};`)
  .join("\n");

const output = `// AUTO-GENERATED by scripts/gen-types from engine/tonalia_engine/rpc_schema.py.
// Do not edit by hand: change the pydantic models and run \`scripts/gen-types\`.

${body}

export interface RpcMethods {
${methods}
}

export interface RpcNotifications {
${notifications}
}

export interface RpcEvents {
${events}
}
`;

if (process.argv.includes("--check")) {
  const current = readFileSync(outFile, "utf8");
  if (current !== output) {
    console.error("rpc.types.ts is out of date: run scripts/gen-types");
    process.exit(1);
  }
  console.log("rpc.types.ts is up to date");
} else {
  writeFileSync(outFile, output);
  console.log(`wrote ${outFile}`);
}
